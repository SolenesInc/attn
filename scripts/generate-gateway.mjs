import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const source = 'internal/protocol/schema/gateway.tsp';
const directory = 'internal/protocol/schema/tsp-output-gateway/json-schema';
const annotations = new Set(['$schema', '$id', 'title', 'description', 'examples', '$comment']);

function contract(value) {
  if (Array.isArray(value)) return value.map(contract);
  if (value === null || typeof value !== 'object') return value;
  return Object.fromEntries(Object.keys(value).sort().filter(key => !annotations.has(key)).map(key => [key, key === 'properties' ? fields(value[key]) : contract(value[key])]));
}

function fields(properties) {
  return Object.fromEntries(Object.keys(properties).sort().map(name => [name, contract(properties[name])]));
}

const version = /^const GATEWAY_API_VERSION = (\d+);$/m.exec(readFileSync(source, 'utf8'));
if (!version) throw new Error(`${source} must declare: const GATEWAY_API_VERSION = <integer>;`);

const files = readdirSync(directory).filter(file => file.endsWith('.json')).sort();
if (files.length === 0) throw new Error(`No gateway schemas found in ${directory}; compile ${source} first.`);
const schema = Object.fromEntries(files.map(file => [file.replace(/\.json$/, ''), contract(JSON.parse(readFileSync(`${directory}/${file}`, 'utf8')))]));

writeFileSync('internal/protocol/gateway/schema.json', JSON.stringify(schema, null, 2) + '\n');
writeFileSync('internal/protocol/gateway/version.go', `// Code generated by make generate-types. DO NOT EDIT.\n\npackage gateway\n\nconst APIVersion = ${version[1]}\n`);
const typescript = 'app/src/types/gatewayGenerated.ts';
const unusedMapHelper = 'function m(additional: any) {\n    return { props: [], additional };\n}\n\n';
const generated = readFileSync(typescript, 'utf8');
if (!/[^a-zA-Z_]m\(/.test(generated.replace(unusedMapHelper, ''))) writeFileSync(typescript, generated.replace(unusedMapHelper, ''));
writeFileSync('app/src/types/gatewayVersion.ts', `// Code generated by make generate-types. DO NOT EDIT.\n\nexport const GATEWAY_API_VERSION = ${version[1]};\n`);
