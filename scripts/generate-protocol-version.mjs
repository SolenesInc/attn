import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const annotations = new Set(['title', 'description', 'examples', '$comment']);
const schemaMaps = new Set(['properties', 'patternProperties', '$defs', 'definitions', 'dependentSchemas']);
const schemas = new Set(['items', 'prefixItems', 'contains', 'additionalProperties', 'unevaluatedProperties', 'propertyNames', 'not', 'if', 'then', 'else', 'allOf', 'anyOf', 'oneOf']);
const unordered = new Set(['required', 'enum', 'allOf', 'anyOf', 'oneOf', 'type']);

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value === null || typeof value !== 'object') return value;
  return Object.fromEntries(Object.keys(value).sort().map(key => [key, canonical(value[key])]));
}

function wireSchema(value) {
  if (Array.isArray(value)) return value.map(wireSchema);
  if (value === null || typeof value !== 'object') return value;
  return Object.fromEntries(Object.keys(value).sort().filter(key => !annotations.has(key)).map(key => {
    let item = value[key];
    if (schemaMaps.has(key)) {
      item = Object.fromEntries(Object.keys(item).sort().map(name => [name, wireSchema(item[name])]));
    } else if (schemas.has(key)) {
      item = wireSchema(item);
    } else {
      item = canonical(item);
    }
    if (unordered.has(key) && Array.isArray(item)) {
      item.sort((a, b) => {
        const left = JSON.stringify(a);
        const right = JSON.stringify(b);
        return left < right ? -1 : left > right ? 1 : 0;
      });
    }
    return [key, item];
  }));
}

const directory = 'internal/protocol/schema/tsp-output/json-schema';
const files = readdirSync(directory).filter(file => file.endsWith('.json')).sort();
if (files.length === 0) throw new Error(`No protocol schemas found in ${directory}; compile TypeSpec first.`);
const contract = files.map(file => [file, wireSchema(JSON.parse(readFileSync(`${directory}/${file}`, 'utf8')))]);
const version = createHash('sha256').update(JSON.stringify(contract)).digest('hex').slice(0, 12);

writeFileSync('internal/protocol/protocol_version.go', `// Code generated by make generate-types. DO NOT EDIT.\n\npackage protocol\n\nconst ProtocolVersion = "${version}"\n`);
writeFileSync('app/src/types/protocolVersion.ts', `// Code generated by make generate-types. DO NOT EDIT.\n\nexport const PROTOCOL_VERSION = '${version}';\n`);

const locators = { home: 'LocatorHome', here: 'LocatorHere', machine: 'LocatorMachine', session: 'LocatorSession', terminal: 'LocatorTerminal', setting: 'LocatorSetting' };
const initialisms = new Set(['id', 'url', 'sha', 'pr', 'ci']);
const goFieldName = field => field.split('_').map(part => initialisms.has(part) ? part.toUpperCase() : part.charAt(0).toUpperCase() + part.slice(1)).join('');

const placed = [];
for (const [file, schema] of contract) {
  const on = schema['x-on'];
  if (on === undefined) continue;
  const model = file.replace(/\.json$/, '');
  const command = schema.properties?.cmd?.const;
  if (typeof command !== 'string') throw new Error(`${model} carries x-on but has no constant cmd`);
  const alternatives = Array.isArray(on) ? on : [on];
  if (alternatives.length === 0) throw new Error(`${command}: x-on needs a placement`);
  const places = alternatives.map((place, index) => {
    const keys = Object.keys(place);
    if (keys.length !== 1 || !(keys[0] in locators)) throw new Error(`${command}: x-on needs exactly one of ${Object.keys(locators).join(', ')}; got ${JSON.stringify(place)}`);
    const locator = keys[0];
    const last = index === alternatives.length - 1;
    if (locator === 'home' || locator === 'here') {
      if (place[locator] !== true || !last) throw new Error(`${command}: x-on ${locator} takes true and must be last`);
      return { locator, field: '', optional: false };
    }
    const field = place[locator];
    if (typeof field !== 'string' || !(field in (schema.properties ?? {}))) {
      throw new Error(`${command}: x-on ${locator} names unknown field ${JSON.stringify(field)}`);
    }
    const optional = !(schema.required ?? []).includes(field);
    if (last && optional) throw new Error(`${command}: the last x-on field ${field} must be required`);
    if (!last && !optional) throw new Error(`${command}: required x-on field ${field} must be last`);
    return { locator, field, optional };
  });
  placed.push({ model, command, places });
}
placed.sort((a, b) => a.command < b.command ? -1 : a.command > b.command ? 1 : 0);

const keyWidth = Math.max(0, ...placed.map(p => JSON.stringify(p.command).length + 1));
const placement = p => `Placement{${locators[p.locator]}, ${JSON.stringify(p.field)}}`;
const lines = [
  '// Code generated by make generate-types. DO NOT EDIT.',
  '',
  'package protocol',
  '',
  'import "encoding/json"',
  '',
  'type Locator int',
  '',
  'const (',
  '\tLocatorHome Locator = iota + 1',
  '\tLocatorHere',
  '\tLocatorMachine',
  '\tLocatorSession',
  '\tLocatorTerminal',
  '\tLocatorSetting',
  ')',
  '',
  'type Placement struct {',
  '\tLocator Locator',
  '\tField   string',
  '}',
  '',
  'type Placed interface {',
  '\tCommandName() string',
  '\tPlacement() Placement',
  '\tLocate() string',
  '}',
  '',
  'var Placements = map[string][]Placement{',
  ...placed.map(p => `\t${`${JSON.stringify(p.command)}:`.padEnd(keyWidth)} {${p.places.map(place => placement(place)).join(', ')}},`),
  '}',
];
lines.push('',
  'func SocketPlacement(command string, frame []byte) (Placement, bool) {',
  '\tplaces, declared := Placements[command]',
  '\tif !declared {',
  '\t\treturn Placement{}, false',
  '\t}',
  '\tif len(places) == 1 {',
  '\t\treturn places[0], true',
  '\t}',
  '\tvar fields map[string]json.RawMessage',
  '\tif json.Unmarshal(frame, &fields) != nil {',
  '\t\treturn Placement{}, false',
  '\t}',
  '\tfor _, place := range places[:len(places)-1] {',
  '\t\tif raw, present := fields[place.Field]; present && string(raw) != "null" {',
  '\t\t\treturn place, true',
  '\t\t}',
  '\t}',
  '\treturn places[len(places)-1], true',
  '}',
);
for (const p of placed) {
  const select = expression => p.places.map((place, index) => {
    const value = expression(place);
    if (index === p.places.length - 1) return `\treturn ${value}`;
    return `\tif m.${goFieldName(place.field)} != nil {\n\t\treturn ${value}\n\t}`;
  }).join('\n');
  lines.push(
    '',
    `func (${p.model}) CommandName() string {\n\treturn ${JSON.stringify(p.command)}\n}`,
    '',
    `func (m ${p.model}) Placement() Placement {\n${select(place => placement(place))}\n}`,
    '',
    `func (m ${p.model}) Locate() string {\n${select(place => place.field === '' ? '""' : `string(${place.optional ? '*' : ''}m.${goFieldName(place.field)})`)}\n}`,
  );
}
writeFileSync('internal/protocol/placement_generated.go', lines.join('\n') + '\n');
