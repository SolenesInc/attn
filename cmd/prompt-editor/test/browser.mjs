import assert from "node:assert/strict";
import { spawn, execFileSync } from "node:child_process";
import { once } from "node:events";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const repo = fileURLToPath(new URL("../../..", import.meta.url));
const require = createRequire(path.join(repo, "app/package.json"));
const { chromium, expect } = require("@playwright/test");
const fixture = await fs.mkdtemp(path.join(os.tmpdir(), "prompt-editor-browser-"));
const artifacts = process.env.PROMPT_EDITOR_ARTIFACTS;
const git = (...args) => execFileSync("git", ["-C", fixture, ...args], { encoding: "utf8", env: { ...process.env, GIT_CONFIG_GLOBAL: os.devNull, GIT_CONFIG_NOSYSTEM: "1" } }).trim();
const root = path.join(fixture, "internal/prompts");
const wake = path.join(root, "content/crew/wake.md");
let server, browser, context;
const consoleErrors = [];
try {
  await fs.mkdir(root, { recursive: true });
  await fs.cp(path.join(repo, "internal/prompts/content"), path.join(root, "content"), { recursive: true });
  git("init", "-b", "next");
  const commit = () => {
    git("add", ".");
    git("-c", "user.name=Editor browser test", "-c", "user.email=editor@example.test", "commit", "--no-gpg-sign", "-m", "Prompt fixture");
    return git("rev-parse", "HEAD");
  };
  const legacy = commit();
  const manifest = JSON.parse(await fs.readFile(path.join(repo, "internal/prompts/catalog.generated.json"), "utf8"));
  delete manifest.definitions_hash;
  const currentManifest = JSON.stringify(manifest);
  const crew = manifest.recipients.find((r) => r.id === "crew");
  const wakeEvent = crew.events.find((e) => e.id === "wake");
  wakeEvent.delivery = "launch_instructions";
  wakeEvent.body = { kind: "compose", children: [wakeEvent.body, { kind: "input", field: { name: "old_note", kind: "text", description: "A base-only input" } }] };
  crew.events.push({ id: "retired", delivery: "user_message", description: "Removed event", body: { kind: "text", id: "retired", source: "content/retired.md" } });
  await fs.writeFile(path.join(root, "catalog.generated.json"), JSON.stringify(manifest));
  await fs.writeFile(path.join(root, "content/retired.md"), "Retired guidance.\n");
  await fs.writeFile(wake, "Wake from the common ancestor.\n");
  const ancestor = commit();
  git("checkout", "-b", "feature");
  await fs.writeFile(path.join(root, "catalog.generated.json"), currentManifest);
  await fs.writeFile(wake, "Wake from the feature branch.\n");
  const head = commit();
  git("checkout", "next");
  await fs.writeFile(wake, "Wake from the next branch tip.\n");
  const tip = commit();
  git("checkout", "feature");
  const binary = process.env.PROMPT_EDITOR_BIN || path.join(fixture, "prompt-editor");
  if (!process.env.PROMPT_EDITOR_BIN) execFileSync("go", ["build", "-o", binary, "./cmd/prompt-editor"], { cwd: repo, stdio: "inherit" });
  server = spawn(binary, ["--repo", fixture, "--base", "next"], { stdio: ["ignore", "pipe", "pipe"] });
  const url = await new Promise((resolve, reject) => {
    let stdout = "";
    const timer = setTimeout(() => reject(new Error("Editor did not start")), 15000);
    server.once("error", (error) => { clearTimeout(timer); reject(error); });
    server.once("exit", (code) => { clearTimeout(timer); reject(new Error(`Editor exited ${code}`)); });
    server.stdout.on("data", (chunk) => {
      stdout += chunk;
      const match = stdout.match(/http:\/\/127\.0\.0\.1:\d+/);
      if (match) { clearTimeout(timer); resolve(match[0]); }
    });
    server.stderr.on("data", (chunk) => process.stderr.write(chunk));
  });
  if (artifacts) await fs.mkdir(artifacts, { recursive: true });
  browser = await chromium.launch({ headless: true });
  context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, ...(artifacts ? { recordVideo: { dir: artifacts, size: { width: 1440, height: 1000 } } } : {}) });
  const page = await context.newPage();
  page.on("pageerror", (error) => consoleErrors.push(String(error)));
  await page.goto(`${url}/#crew/wake`);
  await expect(page.locator("#base-status")).toContainText(ancestor.slice(0, 8));
  await expect(page.locator("#event-change")).toHaveText("definition changed");
  await page.getByLabel("old_note", { exact: true }).fill("Shared scenario note.");
  await page.getByLabel("Markdown source").fill("Wake from my unsaved draft.\nLiteral <script>text</script> and λ.\n");
  await page.locator("#source-compare").click();
  await page.locator("#prompt-compare").click();
  await expect(page.locator("#source-diff .added .line-text")).toContainText(["Wake from my unsaved draft.", "Literal <script>text</script> and λ."]);
  await expect(page.locator("#source-diff .removed .line-text")).toContainText(["Wake from the common ancestor."]);
  await expect(page.locator("#prompt-diff")).toContainText("Shared scenario note.");
  await expect(page.locator("#delivery")).toContainText("launch instructions → user message");
  assert.equal(await fs.readFile(wake, "utf8"), "Wake from the feature branch.\n");
  if (artifacts) await page.screenshot({ path: path.join(artifacts, "draft-comparison.png") });
  await page.locator("#changed-only").check();
  await expect(page.locator(".event-link").filter({ hasText: /^heartbeat/ })).toHaveCount(0);
  await page.locator("#save").click();
  await expect(page.locator("#global-status")).toHaveText("Checkout sources");
  assert.equal(await fs.readFile(wake, "utf8"), "Wake from my unsaved draft.\nLiteral <script>text</script> and λ.\n");
  await page.locator("#source-edit").click();
  await page.getByLabel("Markdown source").fill("An edit to discard.");
  await page.locator("#reset").click();
  assert.match(await page.getByLabel("Markdown source").inputValue(), /^Wake from my unsaved draft/);
  await page.locator("#source-compare").click();
  await page.locator("#base-mode").selectOption("tip");
  await expect(page.locator("#base-status")).toContainText(tip.slice(0, 8));
  await expect(page.locator("#source-diff")).toContainText("Wake from the next branch tip.");
  await page.locator(".event-link").filter({ hasText: /^retired/ }).click();
  await expect(page.locator("#event-change")).toHaveText("removed");
  await expect(page.locator("#prompt-diff")).toContainText("Retired guidance.");
  await expect(page.locator("#save")).toBeDisabled();
  if (artifacts) await page.screenshot({ path: path.join(artifacts, "removed-event.png") });
  await page.locator("#base-mode").selectOption("merge-base");
  await expect(page.locator("#base-status")).toContainText(ancestor.slice(0, 8));
  await expect(page.locator("#event-name")).toHaveText("retired");
  await expect(page.locator("#prompt-diff")).toContainText("Retired guidance.");
  await page.locator(".event-link").filter({ hasText: /^wake/ }).click();
  await page.locator("#base-ref").fill("does-not-exist");
  await page.locator("#compare-base").click();
  await expect(page.locator("#base-status")).toHaveText("Comparison unavailable");
  await expect(page.locator("#source-diff")).not.toContainText("Wake from the next branch tip.");
  await page.locator("#base-ref").fill(legacy);
  await page.locator("#compare-base").click();
  await expect(page.locator("#base-error")).toContainText("no catalog manifest");
  await expect(page.locator("#prompt-diff")).toContainText("Composed comparison unavailable");
  await expect(page.locator("#source-diff .added")).toContainText(["Wake from my unsaved draft.", "Literal <script>text</script> and λ."]);
  if (artifacts) await page.screenshot({ path: path.join(artifacts, "legacy-base.png") });
  await page.locator("#clear-base").click();
  await expect(page.locator("#base-error")).toBeHidden();
  await page.locator("#prompt-current").click();
  await expect(page.locator("#output")).toContainText("Wake from my unsaved draft.");
  await page.locator("#source-edit").click();
  await page.getByLabel("Markdown source").fill("Stale draft.");
  await fs.writeFile(wake, "External edit.\n");
  await page.locator("#save").click();
  await expect(page.locator("#file-error")).toContainText("file changed on disk");
  assert.equal(await fs.readFile(wake, "utf8"), "External edit.\n");
  page.on("dialog", (dialog) => dialog.accept());
  await page.locator("#reload").click();
  await expect(page.getByLabel("Markdown source")).toHaveValue("External edit.\n");
  let requests = 0;
  page.on("request", () => requests++);
  await expect(page.locator("#output")).toContainText("External edit.");
  const settled = requests;
  const idleBefore = execFileSync("ps", ["-p", String(server.pid), "-o", "rss=", "-o", "time="], { encoding: "utf8" }).trim();
  await page.waitForTimeout(1200);
  const idleAfter = execFileSync("ps", ["-p", String(server.pid), "-o", "rss=", "-o", "time="], { encoding: "utf8" }).trim();
  assert.equal(requests, settled, "editor polls while idle");
  assert.equal(git("rev-parse", "HEAD"), head);
  assert.deepEqual(consoleErrors, []);
  await page.setViewportSize({ width: 780, height: 900 });
  if (artifacts) await page.screenshot({ path: path.join(artifacts, "narrow-editor.png"), fullPage: true });
  console.log(JSON.stringify({ status: "passed", ancestor, head, tip, legacy, consoleErrors, idleRequests: requests - settled, idleBefore, idleAfter, artifacts }, null, 2));
} finally {
  if (context) await context.close();
  if (browser) await browser.close();
  if (server && server.exitCode === null) { server.kill("SIGTERM"); await once(server, "exit"); }
  await fs.rm(fixture, { recursive: true, force: true });
}
