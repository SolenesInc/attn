package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/victorarias/attn/internal/viewlang/catalog"
)

func main() {
	if len(os.Args) != 5 {
		fatal(fmt.Errorf("usage: viewgen <fixtures directory> <view.tsp> <reference.md> <view_parts.rs>"))
	}
	reference, err := writeReference(os.Args[1])
	if err != nil {
		fatal(err)
	}
	for path, text := range map[string]string{os.Args[2]: typeSpec(), os.Args[3]: reference, os.Args[4]: rustTable()} {
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			fatal(err)
		}
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "viewgen:", err)
	os.Exit(1)
}

func wire(name string) string { return strings.ReplaceAll(name, "-", "_") }

func pascal(name string) string {
	var out strings.Builder
	for _, word := range strings.FieldsFunc(name, func(r rune) bool { return r == '-' || r == '_' }) {
		out.WriteString(strings.ToUpper(word[:1]) + word[1:])
	}
	return out.String()
}

func property(name, kind string, required bool) string {
	optional := "?"
	if required {
		optional = ""
	}
	return fmt.Sprintf("  `%s`%s: %s;\n", wire(name), optional, kind)
}

func argType(kind catalog.ArgKind) string {
	switch kind {
	case catalog.ItemsArg:
		return "ViewItems"
	case catalog.FieldArg, catalog.KeyedFieldArg:
		return "string[]"
	case catalog.CommandArg:
		return "ViewCommandCall"
	case catalog.FlagArg:
		return "boolean"
	}
	return "string"
}

func slotType(kind catalog.SlotKind) string {
	switch kind {
	case catalog.TemplateSlot:
		return "ViewTemplate"
	case catalog.CommandSlot:
		return "ViewCommandCall"
	case catalog.CommandsSlot:
		return "ViewCommandCall[]"
	}
	return "string"
}

func bodyProperties(part catalog.Part) string {
	switch part.Body {
	case catalog.ProseBody:
		return property("text", "ViewTemplate", true)
	case catalog.MediaBody:
		return property("label", "ViewTemplate", true) + property("file", "ViewTemplate", true)
	case catalog.TasksBody:
		return property("tasks", "ViewTask[]", true)
	case catalog.QuestionBody:
		return property("question", "AskQuestion", true)
	case catalog.TextQuestionBody:
		return property("question", "AskQuestion", true) + property("value", "ViewTemplate", false)
	case catalog.MediaPairBody:
		return property("media", "ViewMedia[]", true)
	case catalog.FieldsBody:
		return property("fields", "ViewStoreField[]", false)
	case catalog.FactsBody:
		return property("facts", "ViewFact[]", true)
	case catalog.SlotsBody:
		return property("slots", "ViewPart"+pascal(part.Name)+"Slots", true)
	case catalog.TableBody:
		return property("columns", "ViewColumn[]", true)
	case catalog.BlocksBody:
		return property("blocks", "ViewPart[]", true)
	case catalog.TextBody:
		return property("text", "string", false)
	case catalog.ControlsBody:
		return property("controls", "ViewCommandCall[]", true)
	case catalog.CommandsBody:
		return property("commands", "ViewOwnCommand[]", true)
	}
	return ""
}

func enum(name string, members []catalog.Named) string {
	var out strings.Builder
	fmt.Fprintf(&out, "enum %s {\n", name)
	for _, member := range members {
		if wire(member.Name) == member.Name {
			fmt.Fprintf(&out, "  %s,\n", member.Name)
		} else {
			fmt.Fprintf(&out, "  %s: %q,\n", wire(member.Name), member.Name)
		}
	}
	out.WriteString("}\n\n")
	return out.String()
}

const fixedModels = `alias ViewTemplate = ViewTemplatePiece[];

model ViewProblem {
  line: int32;
  text: string;
  fix: string;
}

model ViewTemplatePiece {
  text?: string;
  field?: string[];
  format?: ViewFormat;
}

model ViewItems {
  field?: string[];
  file?: string;
}

model ViewCommandCall {
  command: string;
  args: string[];
}

model ViewMedia {
  label: ViewTemplate;
  file: ViewTemplate;
}

model ViewTask {
  text: ViewTemplate;
  checked: boolean;
}

model ViewFact {
  label: string;
  value: ViewTemplate;
}

model ViewColumn {
  header: string;
  cell: ViewTemplate;
}

model ViewOwnCommand {
  name: string;
  written: string;
  confirm?: ViewTemplate;
  program: string;
  args: ViewTemplate[];
}

model ViewStoreField {
  name: string;
  type: ViewStoreType;
}

`

func typeSpec() string {
	var out strings.Builder
	out.WriteString("// Code generated by make generate-types from internal/catalog. DO NOT EDIT.\n\nnamespace Protocol;\n\n")
	out.WriteString(fixedModels)
	out.WriteString(enum("ViewFormat", catalog.Formats))
	out.WriteString(enum("ViewStoreType", catalog.StoreTypes))
	out.WriteString("model ViewPart {\n  name: string;\n  line: int32;\n  problem?: ViewProblem;\n")
	for _, part := range catalog.Parts {
		out.WriteString(property(part.Name, "ViewPart"+pascal(part.Name), false))
	}
	out.WriteString("}\n")
	for _, part := range catalog.Parts {
		fmt.Fprintf(&out, "\nmodel ViewPart%s {\n", pascal(part.Name))
		for _, arg := range part.Args {
			out.WriteString(property(arg.Name, argType(arg.Kind), arg.Required))
		}
		out.WriteString(bodyProperties(part))
		out.WriteString("}\n")
		if part.Body == catalog.SlotsBody {
			fmt.Fprintf(&out, "\nmodel ViewPart%sSlots {\n", pascal(part.Name))
			for _, slot := range part.Slots {
				out.WriteString(property(slot.Name, slotType(slot.Kind), false))
			}
			out.WriteString("}\n")
		}
	}
	return out.String()
}

func rustTable() string {
	var out strings.Builder
	out.WriteString("// Code generated by make generate-types from internal/catalog. DO NOT EDIT.\n\npub struct ViewParts<T> {\n")
	for _, part := range catalog.Parts {
		fmt.Fprintf(&out, "    pub %s: T,\n", wire(part.Name))
	}
	out.WriteString("}\n\nimpl<T> ViewParts<T> {\n    #[must_use]\n    pub fn get(&self, name: &str) -> Option<&T> {\n        match name {\n")
	for _, part := range catalog.Parts {
		fmt.Fprintf(&out, "            %q => Some(&self.%s),\n", part.Name, wire(part.Name))
	}
	out.WriteString("            _ => None,\n        }\n    }\n}\n")
	return out.String()
}

func written(part catalog.Part) string {
	if part.Written != "" {
		return part.Written
	}
	words := []string{part.Opener()}
	for _, arg := range part.Args {
		if arg.Required {
			words = append(words, arg.Form())
		}
	}
	return strings.Join(words, " ")
}

func fence(text string) string {
	marker := "```"
	for strings.Contains(text, marker) {
		marker += "`"
	}
	return marker + "markdown\n" + strings.TrimRight(text, "\n") + "\n" + marker + "\n"
}

func example(fixtures, name string) (string, error) {
	text, err := os.ReadFile(filepath.Join(fixtures, name))
	if err != nil {
		return "", fmt.Errorf("the example of a part: %w", err)
	}
	return fence(string(text)), nil
}

func bullets(out *strings.Builder, heading string, items []string) {
	if len(items) == 0 {
		return
	}
	fmt.Fprintf(out, "%s:\n\n", heading)
	for _, item := range items {
		fmt.Fprintf(out, "- %s\n", item)
	}
	out.WriteString("\n")
}

func namedRows(items []catalog.Named) []string {
	rows := make([]string, 0, len(items))
	for _, item := range items {
		rows = append(rows, fmt.Sprintf("`%s`: %s.", item.Name, item.Doc))
	}
	return rows
}

func writeReference(fixtures string) (string, error) {
	var out strings.Builder
	out.WriteString("<!-- Code generated by make generate-types from internal/viewlang/catalog. DO NOT EDIT. -->\n\n# Views\n\n")
	out.WriteString("A view is a markdown file that attn draws in a tile. It holds prose and parts. A part opens with `:::name` and its arguments on a line of their own, and closes with a line that holds only `:::`. A part that holds other parts opens with four colons and closes with `::::`. Put an argument's value in quotes when it holds a space, as in `run=\"scripts/weather.sh Stockholm\"`.\n\n")
	out.WriteString("A view's data is what its `:::data` parts provide. In a part, `{field}` is a value from that data, a field inside a field is written `{ci.state}`, and `{field|format}` draws the value in a format. In a list, a table or a four-colon part, `{field}` is a field of each item.\n\n")
	fmt.Fprintf(&out, "This is language version %d. When attn keeps a view, it writes `<!-- attn-view %d -->` on the view's first line. Do not write that line in a view for one task: a view without it is read as the current version.\n\n", catalog.Language, catalog.Language)
	out.WriteString("Below, Keys are the keys the user presses on a part, and Reports is what the part adds to the answers the user sends back to the agent that opened the view.\n\n")
	out.WriteString("When the user sends, attn writes the answers to `<view>.responses.json` beside the view and types one line into your conversation that sums them up and names the file. In the file, `path` names the view, `answers` holds the answers outside `::::each` and `::::one-by-one` by the question's name, and `rows` holds each item's answers by the item's `id`, or by its place from 1 when it has none. A choice is its label, a `question-multi` answer is a list of labels, a written answer is its text, and a `question-file` answer is a list with one entry per file, each telling you to save the file with `attn agent attachment <id> --out <path>`. A `one-by-one` item also has a `verdict`: `kept`, `changed` when the user rewrote a `Value:` text, or `skipped`. Items the user never reached are left out. The user can send again, and the file then holds every answer so far.\n\n")
	out.WriteString("## Parts\n\n| Part | Written | Draws |\n|---|---|---|\n")
	for _, part := range catalog.Parts {
		fmt.Fprintf(&out, "| %s | `%s` | %s |\n", part.Name, written(part), strings.ReplaceAll(part.Summary, "|", "\\|"))
	}
	out.WriteString("\nDo not name a part `script`: attn reserves the name and refuses it.\n\n## Example\n\n")
	whole, err := example(fixtures, "check-transcripts.md")
	if err != nil {
		return "", err
	}
	out.WriteString(whole)
	out.WriteString("\n## Where a view's values come from\n\nEach `:::data` part names one source. A `:::data` part without `as=` puts its values at the top of the view's data, and with `as=` they appear under that field. Two parts cannot use the same field. A store's values appear under the store's name. The `data` section below lists the arguments.\n\n")
	out.WriteString("Opening a view runs nothing. The tile names each command of `run=` and `:::commands`, and waits until the user presses `r` to start them. When a command line or the script it names changes, attn stops that command and waits for the user again.\n\n")
	bullets(&out, "attn's data sets, for `attn=`", namedRows(catalog.DataSets))
	bullets(&out, "The types of a store's fields", namedRows(catalog.StoreTypes))
	bullets(&out, "The formats, written `{field|format}`", namedRows(catalog.Formats))
	out.WriteString("## Commands a view can run\n\nA row's `press:`, `controls:` and `group-controls:` slots, `:::controls` and `:::entry` name commands, such as `press: open`.\n\n")
	bullets(&out, "attn's commands", namedRows(catalog.Commands))
	var store []string
	for _, command := range catalog.StoreCommands {
		usage := command.Name
		if command.Field {
			usage += " <field>"
		}
		if command.Value {
			usage += " <value>"
		}
		store = append(store, fmt.Sprintf("`%s`: %s.", usage, command.Doc))
	}
	bullets(&out, "The commands of a view with a store, such as `press: toggle done` and `:::entry add text`", store)
	out.WriteString("A view defines its own commands in `:::commands`. Each is a program and its arguments, run on the view's machine in the view's folder and never through a shell. Fields such as `{id}` in its arguments take the values of the row whose control the user pressed, and each reaches the program as one argument, whatever characters it holds. `:::entry` gives it the typed text as its last argument. `confirm=\"Rerun {name}?\"` before the program asks the user first. The command runs only once the user starts the view's commands with `r` on its tile, and its control shows while it runs, and whether it finished or failed. A view's own command cannot take the name of one of attn's commands or of a store's commands.\n")
	for _, part := range catalog.Parts {
		fmt.Fprintf(&out, "\n## %s\n\n`%s`\n\n%s\n\n", part.Name, written(part), part.Summary)
		var args []string
		for _, arg := range part.Args {
			need := ""
			if arg.Required {
				need = " Required."
			}
			args = append(args, fmt.Sprintf("`%s`: %s.%s", arg.Form(), arg.Doc, need))
		}
		bullets(&out, "Arguments", args)
		var slots []string
		for _, slot := range part.Slots {
			slots = append(slots, fmt.Sprintf("`%s`: %s.", slot.Name, slot.Doc))
		}
		bullets(&out, "Slots", slots)
		if part.Keys != "" {
			fmt.Fprintf(&out, "Keys: %s.\n\n", part.Keys)
		}
		if part.Reports != "" {
			fmt.Fprintf(&out, "Reports: %s.\n\n", part.Reports)
		}
		if part.TopOnly {
			out.WriteString("It goes at the top level of a view, not inside a four-colon part.\n\n")
		}
		text, err := example(fixtures, part.Example)
		if err != nil {
			return "", err
		}
		out.WriteString(text)
	}
	return out.String(), nil
}
