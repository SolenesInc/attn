package main

import (
	"fmt"
	"os"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fatal(fmt.Errorf("usage: cligen <go_values.rs> <corpus directory>"))
	}
	var out strings.Builder
	out.WriteString("// Code generated by make generate-types. DO NOT EDIT.\n\n")
	out.WriteString("#![allow(clippy::all, clippy::pedantic)]\n\n")
	writeConstants(&out)
	writeSettings(&out)
	writePrompts(&out)
	writePrintableRanges(&out)
	if err := os.WriteFile(os.Args[1], []byte(out.String()), 0o644); err != nil {
		fatal(err)
	}
	if err := writeCorpus(os.Args[2]); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "cligen:", err)
	os.Exit(1)
}

func rustString(value string) string {
	var out strings.Builder
	out.WriteByte('"')
	for _, r := range value {
		switch {
		case r == '"':
			out.WriteString(`\"`)
		case r == '\\':
			out.WriteString(`\\`)
		case r == '\n':
			out.WriteString(`\n`)
		case r == '\t':
			out.WriteString(`\t`)
		case r == '\r':
			out.WriteString(`\r`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&out, `\u{%x}`, r)
		default:
			out.WriteRune(r)
		}
	}
	out.WriteByte('"')
	return out.String()
}
