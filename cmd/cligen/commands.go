var goInitialisms = map[string]string{"id": "ID", "url": "URL", "pr": "PR"}

func goName(words ...string) string {
	var out strings.Builder
	for _, word := range words {
		for _, part := range strings.FieldsFunc(word, func(r rune) bool { return r == ' ' || r == '-' || r == '_' }) {
			if upper, ok := goInitialisms[part]; ok {
				out.WriteString(upper)
				continue
			}
			out.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return out.String()
}

type valueKind int

const (
	valueText valueKind = iota
	valueInt
	valueBool
	valueJSON
)

func (g *generator) valueKind(a catalog.Arg) valueKind {
	switch g.c.ArgType(a).Schema["type"] {
	case "integer":
		return valueInt
	case "boolean":
		return valueBool
	case "object":
		return valueJSON
	default:
		return valueText
	}
}

func (g *generator) goArgType(a catalog.Arg) string {
	if a.List {
		return "[]string"
	}
	switch g.valueKind(a) {
	case valueInt:
		return "*int64"
	case valueBool:
		return "bool"
	case valueJSON:
		return "json.RawMessage"
	default:
		return "string"
	}
}

func writeCommandTables(c *catalog.Catalog, cliRoot, goRoot string) error {
	g := generator{c: c}
	var runs strings.Builder
	runs.WriteString("// Code generated by make generate-types from internal/catalog. DO NOT EDIT.\n\npackage protocol\n\n")
	runs.WriteString("// CommandRuns is where each catalog command runs, for run_command's placement.\nvar CommandRuns = map[string]Locator{\n")
	for _, cmd := range c.Commands {
		if !cmd.ThroughLayer() {
			continue
		}
		locator := "LocatorHome"
		if cmd.Runs == catalog.RunsHere {
			locator = "LocatorHere"
		}
		fmt.Fprintf(&runs, "\t%q: %s,\n", cmd.Name, locator)
	}
	runs.WriteString("}\n")
	if err := writeGo(filepath.Join(goRoot, "protocol", "commands_generated.go"), runs.String()); err != nil {
		return err
	}

	var args strings.Builder
	args.WriteString("// Code generated by make generate-types from internal/catalog. DO NOT EDIT.\n\npackage command\n\nimport \"encoding/json\"\n\nvar _ json.RawMessage\n\n")
	codes := map[string]bool{}
	for _, cmd := range c.Commands {
		for _, e := range cmd.Errors {
			codes[e.Code] = true
		}
	}
	args.WriteString("const (\n")
	for _, code := range sortedKeys(codes) {
		fmt.Fprintf(&args, "\tCode%s = %q\n", goName(code), code)
	}
	args.WriteString(")\n\n")
	args.WriteString("var specs = map[string]spec{\n")
	for _, cmd := range c.Commands {
		if !cmd.ThroughLayer() {
			continue
		}
		fixes := ""
		if len(cmd.Errors) > 0 {
			var pairs []string
			for _, e := range cmd.Errors {
				pairs = append(pairs, fmt.Sprintf("%q: %q", e.Code, e.Fix))
			}
			fixes = fmt.Sprintf(", fixes: map[string]string{%s}", strings.Join(pairs, ", "))
		}
		fmt.Fprintf(&args, "\t%q: {readOnly: %v, anyone: %v, sessionFlag: %v%s},\n", cmd.Name, cmd.ReadOnly, cmd.Anyone, g.takesSessionFlag(cmd), fixes)
	}
	args.WriteString("}\n")
	for _, cmd := range c.Commands {
		if !cmd.ThroughLayer() {
			continue
		}
		fmt.Fprintf(&args, "\ntype %sArgs struct {\n", goName(cmd.Name))
		for _, a := range cmd.Args {
			fmt.Fprintf(&args, "\t%s %s `json:\"%s,omitempty\"`\n", goName(a.Name), g.goArgType(a), a.Name)
		}
		args.WriteString("}\n")
	}
	if err := writeGo(filepath.Join(goRoot, "command", "args_generated.go"), args.String()); err != nil {
		return err
	}

	for _, group := range c.LayerFamilies() {
		rust, err := g.rustTable(group)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(cliRoot, "commands", rustModule(group), "table_generated.rs"), []byte(rust), 0o644); err != nil {
			return err
		}
	}
	topLevel, err := g.rustTopLevel()
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(cliRoot, "commands/top_level_generated.rs"), []byte(topLevel), 0o644)
}

func (g *generator) takesSessionFlag(cmd catalog.Command) bool {
	family, _, _ := strings.Cut(cmd.Name, " ")
	return slices.ContainsFunc(g.family(family).Flags, func(f catalog.Flag) bool { return f.Name == "session" })
}

func (g *generator) family(name string) *catalog.Group {
	if group, ok := g.c.Group(name); ok {
		return group
	}
	bare, _ := g.c.Command(name)
	return &catalog.Group{Name: name, File: bare.File}
}

func verbOf(family string, cmd *catalog.Command) string {
	if cmd.Name == family {
		return ""
	}
	return strings.TrimPrefix(cmd.Name, family+" ")
}

func (g *generator) rustTopLevel() (string, error) {
	var out strings.Builder
	out.WriteString("// Code generated by make generate-types from internal/catalog. DO NOT EDIT.\n\n#![allow(clippy::all, clippy::pedantic)]\n\n")
	out.WriteString("pub struct TopLevel {\n    pub name: &'static str,\n    pub usage: &'static str,\n    pub summary: &'static str,\n    pub hidden: bool,\n}\n\n")
	out.WriteString("#[rustfmt::skip]\npub const TOP_LEVEL: &[TopLevel] = &[\n")
	for _, top := range g.c.TopLevel() {
		fmt.Fprintf(&out, "    TopLevel { name: %s, usage: %s, summary: %s, hidden: %v },\n",
			rustString(top.Name), rustString(g.topLevelUsage(top)), rustString(strings.TrimSpace(top.Summary)), top.Hidden)
	}
	out.WriteString("];\n")
	return out.String(), g.fail()
}

func (g *generator) topLevelUsage(top catalog.TopLevel) string {
	switch {
	case top.Group != nil:
		return strings.TrimSpace(top.Name + " " + top.Group.Usage)
	case top.Command.ThroughLayer():
		return g.usage("", top.Command)
	default:
		return strings.TrimSpace(top.Name + " " + top.Command.Usage)
	}
}

func writeGo(path, source string) error {
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return os.WriteFile(path, formatted, 0o644)
}

func (g *generator) rustCLI(a catalog.Arg) string {
	switch {
	case a.CLI == "pos":
		return "Cli::Pos"
	case a.CLI == "rest":
		return "Cli::Rest"
	case a.CLI == "-m+":
		return "Cli::SplitRest"
	case strings.Contains(a.CLI, "|"):
		var pairs []string
		flags := strings.Split(a.CLI, "|")
		for i, flag := range flags {
			pairs = append(pairs, fmt.Sprintf("(%s, %s)", rustString(strings.TrimLeft(flag, "-")), rustString(a.Values[i])))
		}
		return fmt.Sprintf("Cli::Choice(&[%s])", strings.Join(pairs, ", "))
	default:
		return fmt.Sprintf("Cli::Flag(%s)", rustString(strings.TrimLeft(a.CLI, "-")))
	}
}

func (g *generator) rustTable(group string) (string, error) {
	var out strings.Builder
	out.WriteString("// Code generated by make generate-types from internal/catalog. DO NOT EDIT.\n\n#![allow(clippy::all, clippy::pedantic, unused_imports)]\n\nuse crate::command::{Arg, Cli, Command, Source, Value};\n\n")
	var flags []string
	for _, f := range g.family(group).Flags {
		flags = append(flags, rustString(f.Name))
	}
	fmt.Fprintf(&out, "pub const FLAGS: &[&str] = &[%s];\n\n#[rustfmt::skip]\npub const COMMANDS: &[Command] = &[\n", strings.Join(flags, ", "))
	kinds := map[valueKind]string{valueText: "Value::Text", valueInt: "Value::Int", valueBool: "Value::Bool", valueJSON: "Value::Json"}
	for _, cmd := range g.c.FamilyCommands(group) {
		for _, a := range cmd.Args {
			if strings.Contains(a.CLI, "|") && len(a.Values) != len(strings.Split(a.CLI, "|")) {
				return "", fmt.Errorf("catalog: %s: %s: arg %q maps %d flags to %d values", cmd.File, cmd.Name, a.Name, len(strings.Split(a.CLI, "|")), len(a.Values))
			}
		}
		var usage []string
		for _, e := range cmd.Errors {
			if e.Usage {
				usage = append(usage, rustString(e.Code))
			}
		}
		fmt.Fprintf(&out, "    Command {\n        name: %s,\n        result: %v,\n        usage: &[%s],\n        args: &[\n",
			rustString(verbOf(group, cmd)), cmd.Result != "", strings.Join(usage, ", "))
		for _, a := range cmd.Args {
			source := "Source::Given"
			switch {
			case a.File:
				source = "Source::File"
			case a.Stdin:
				source = "Source::Stdin"
			}
			fmt.Fprintf(&out, "            Arg { name: %s, cli: %s, value: %s, source: %s, required: %v, list: %v },\n",
				rustString(a.Name), g.rustCLI(a), kinds[g.valueKind(a)], source, a.Required, a.List)
		}
		out.WriteString("        ],\n    },\n")
	}
	out.WriteString("];\n")
	return out.String(), nil
}
