func shouldLogWSCommand(cmd string) bool {
	meta, ok := CommandMeta[cmd]
	if !ok {
		return true
	}
	return meta.Log
}

func blocksDuringRecovery(cmd string) bool {
	meta, ok := CommandMeta[cmd]
	if !ok {
		return false
	}
	return meta.BlocksDuringRecovery
}
