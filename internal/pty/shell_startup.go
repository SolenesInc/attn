package pty

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

type shellPaneLaunch struct {
	command    *exec.Cmd
	env        []string
	overlayDir string
}

func removeShellOverlay(dir string) {
	if dir == "" {
		return
	}
	_ = os.RemoveAll(dir)
}

type shellStartupStrategy func(shellPath string, env []string, attnDir string) (shellPaneLaunch, error)

var shellStartupStrategies = map[string]shellStartupStrategy{
	"zsh":  prepareZshShellPaneLaunch,
	"bash": prepareBashShellPaneLaunch,
	"sh":   prepareShShellPaneLaunch,
	"fish": prepareFishShellPaneLaunch,
}

// shellKind names the startup strategy a shell gets: the first of its names, as invoked and then resolved, that has
// one. /bin/sh linked to bash is "sh", because bash invoked as sh starts in POSIX mode.
func shellKind(shellPath string) string {
	for _, name := range shellNames(shellPath) {
		if _, ok := shellStartupStrategies[name]; ok {
			return name
		}
	}
	return ""
}

func prepareShellPaneLaunch(shellPath string, env []string, attnDir string) (shellPaneLaunch, error) {
	if strategy, ok := shellStartupStrategies[shellKind(shellPath)]; ok {
		return strategy(shellPath, env, attnDir)
	}
	return shellPaneLaunch{
		command: exec.Command(shellPath, "-l"),
		env:     append([]string(nil), env...),
	}, nil
}

func shellNames(shellPath string) []string {
	names := []string{strings.TrimSuffix(filepath.Base(shellPath), ".exe")}
	if resolved, err := filepath.EvalSymlinks(shellPath); err == nil {
		resolvedName := strings.TrimSuffix(filepath.Base(resolved), ".exe")
		if resolvedName != names[0] {
			names = append(names, resolvedName)
		}
	}
	return names
}

func prepareFishShellPaneLaunch(shellPath string, env []string, attnDir string) (shellPaneLaunch, error) {
	if attnDir == "" {
		return shellPaneLaunch{command: exec.Command(shellPath, "-l"), env: env}, nil
	}
	dir := shellQuote(attnDir)
	return shellPaneLaunch{
		command: exec.Command(shellPath, "-l", "-C", "set -gx PATH "+dir+" (string match -v -- "+dir+" $PATH)"),
		env:     env,
	}, nil
}

func prepareZshShellPaneLaunch(shellPath string, env []string, attnDir string) (shellPaneLaunch, error) {
	overlay, err := os.MkdirTemp("", "attn-zsh-startup-")
	if err != nil {
		return shellPaneLaunch{}, fmt.Errorf("create zsh startup overlay: %w", err)
	}
	for file, content := range map[string]string{".zshenv": zshStartupEnv, zshIntegrationFile: zshOSC133Integration} {
		if err := os.WriteFile(filepath.Join(overlay, file), []byte(content), 0o600); err != nil {
			_ = os.RemoveAll(overlay)
			return shellPaneLaunch{}, fmt.Errorf("write zsh startup overlay %s: %w", file, err)
		}
	}
	startEnv := []string{
		"ZDOTDIR=" + overlay,
		"ATTN_SHELL_INIT_DIR=" + overlay,
		"ATTN_SHELL_ATTN_DIR=" + attnDir,
	}
	if userZdotdir, set := LookupEnv(env, "ZDOTDIR"); set {
		startEnv = append(startEnv, "ATTN_SHELL_USER_ZDOTDIR="+userZdotdir)
	}
	return shellPaneLaunch{
		command:    exec.Command(shellPath, "-l"),
		env:        MergeEnvironment(env, startEnv),
		overlayDir: overlay,
	}, nil
}

const (
	zshIntegrationFile  = "attn-osc133.zsh"
	bashIntegrationFile = "attn-osc133.bash"
)

const zshOSC133Integration = `# Generated by attn. Emit OSC 133 prompt/command marks so attn can read the
# shell's state and group command blocks. Opt out by exporting
# ATTN_NO_SHELL_INTEGRATION=1.
[[ -o interactive ]] || return 0

_attn_osc133_precmd() {
  local attn_status=$?
  if [[ -n ${_attn_osc133_ran-} ]]; then
    unset _attn_osc133_ran
    builtin printf '\033]133;D;%d\007' "$attn_status"
  fi
  local attn_pwd=$PWD
  attn_pwd=${attn_pwd//\%/%25}
  attn_pwd=${attn_pwd//\#/%23}
  attn_pwd=${attn_pwd//\?/%3F}
  attn_pwd=${attn_pwd//$'\e'/%1B}
  attn_pwd=${attn_pwd//$'\a'/%07}
  attn_pwd=${attn_pwd//$'\n'/%0A}
  attn_pwd=${attn_pwd//$'\r'/%0D}
  builtin printf '\033]7;file://localhost%s\007' "$attn_pwd"
  builtin printf '\033]133;A\007'
}
_attn_osc133_preexec() {
  typeset -g _attn_osc133_ran=1
  # cmdline_url is percent-encoded just enough to survive the OSC payload:
  # '%' so decoding is unambiguous, ';' (the payload field separator), and the
  # control bytes that would terminate or corrupt the sequence. Everything
  # else, UTF-8 included, passes through raw.
  local cmd=$1
  cmd=${cmd//\%/%25}
  cmd=${cmd//\;/%3B}
  cmd=${cmd//$'\e'/%1B}
  cmd=${cmd//$'\a'/%07}
  cmd=${cmd//$'\n'/%0A}
  cmd=${cmd//$'\r'/%0D}
  builtin printf '\033]133;C;cmdline_url=%s\007' "$cmd"
}

# Prepended, not appended: the exit status a precmd hook sees is whatever the
# previous hook left in $?, so the reporter must run before the user's hooks.
# The filter makes re-sourcing idempotent.
typeset -ga precmd_functions preexec_functions
precmd_functions=(_attn_osc133_precmd ${precmd_functions:#_attn_osc133_precmd})
preexec_functions=(_attn_osc133_preexec ${preexec_functions:#_attn_osc133_preexec})
`

const bashOSC133Integration = `# Generated by attn. Emit OSC 133 prompt/command marks so attn can read the
# shell's state and group command blocks. Opt out by exporting
# ATTN_NO_SHELL_INTEGRATION=1.
[[ $- == *i* ]] || return 0

# Runs first in PROMPT_COMMAND: the exit status a later element sees is
# whatever the previous element left in $?, so the interactive command's
# status must be captured before anything else runs (the bash-preexec
# precedent). Disarming here keeps a DEBUG fire for the user's own
# PROMPT_COMMAND entries from reading as a command start on a bare Enter.
_attn_osc133_status() {
  _attn_osc133_last_status=$?
  unset _attn_osc133_armed
  if [[ -n ${_attn_osc133_ran-} ]] || [[ ${_attn_osc133_mode-} == fallback && -n ${_attn_osc133_primed-} ]]; then
    unset _attn_osc133_ran
    printf '\033]133;D;%d\007' "${_attn_osc133_last_status:-0}"
  fi
}

# Called once, from the first prompt, with the top-level DEBUG trap listing as
# its argument. The DEBUG trap is the only pre-exec hook every bash has (PS0
# needs 4.4, and macOS ships 3.2), so a free trap is claimed here — installing
# from a function body persists on every bash when no trap existed, and a trap
# the user owns is never touched (bash 3.2 silently restores a startup-time
# trap over one set inside a sourced file, while 5.x lets the sourced file
# clobber it, so installation cannot happen at source time at all). A user-
# owned trap — or extdebug, where a DEBUG handler's return value can make bash
# skip the user's command — selects the fallback: PS0 (where it exists) still
# gives a bare C mark, and D degrades to every prompt after the first since
# nothing tracks whether a command ran.
_attn_osc133_init() {
  if [[ -z $1 ]] && ! shopt -q extdebug; then
    trap '_attn_osc133_preexec' DEBUG
    _attn_osc133_mode=trap
  else
    _attn_osc133_mode=fallback
    PS0="${PS0-}"'\e]133;C\a'
  fi
}

_attn_osc133_precmd() {
  _attn_osc133_primed=1
  local attn_pwd=$PWD
  attn_pwd=${attn_pwd//\%/%25}
  attn_pwd=${attn_pwd//\#/%23}
  attn_pwd=${attn_pwd//\?/%3F}
  attn_pwd=${attn_pwd//$'\e'/%1B}
  attn_pwd=${attn_pwd//$'\a'/%07}
  attn_pwd=${attn_pwd//$'\n'/%0A}
  attn_pwd=${attn_pwd//$'\r'/%0D}
  printf '\033]7;file://localhost%s\007' "$attn_pwd"
  printf '\033]133;A\007'
  _attn_osc133_armed=1
}

# The pre-exec mark. Armed at the end of each prompt cycle, so the first DEBUG
# fire that is a real command — not completion, not our own hooks — is the one
# that marks the start; a compound line marks once, carrying its first simple
# command. The saved $? is returned so the trap is transparent to
# _attn_osc133_status (bash discards the trap's own status, but not if we
# return early through the guards).
_attn_osc133_preexec() {
  local attn_ret=$?
  if [[ -z ${COMP_LINE-} && -n ${_attn_osc133_armed-} ]]; then
    case "$BASH_COMMAND" in
    _attn_osc133_*) ;;
    *)
      unset _attn_osc133_armed
      _attn_osc133_ran=1
      local cmd=$BASH_COMMAND
      cmd=${cmd//\%/%25}
      cmd=${cmd//\;/%3B}
      cmd=${cmd//$'\e'/%1B}
      cmd=${cmd//$'\a'/%07}
      cmd=${cmd//$'\n'/%0A}
      cmd=${cmd//$'\r'/%0D}
      printf '\033]133;C;cmdline_url=%s\007' "$cmd"
      ;;
    esac
  fi
  return "$attn_ret"
}

# The mode probe must stay inline in PROMPT_COMMAND — inside this sourced
# file (or any function body) $(trap -p DEBUG) reads empty whether or not the
# user has a trap, but arguments to a call written at top level are expanded
# at top level, where the listing is truthful. Status capture still comes
# first: the probe would overwrite the interactive command's $?.
_attn_osc133_probe='_attn_osc133_status; [[ -n ${_attn_osc133_mode-} ]] || _attn_osc133_init "$(trap -p DEBUG)"'
if [[ $(declare -p PROMPT_COMMAND 2>/dev/null) == 'declare -a'* ]]; then
  PROMPT_COMMAND=("$_attn_osc133_probe" "${PROMPT_COMMAND[@]}" _attn_osc133_precmd)
else
  PROMPT_COMMAND="$_attn_osc133_probe${PROMPT_COMMAND:+;$PROMPT_COMMAND};_attn_osc133_precmd"
fi
unset _attn_osc133_probe
`

const zshStartupEnv = `# Generated by attn. Hand zsh back the user's ZDOTDIR, run the user's
# .zshenv, and put the active attn first once every startup file has run.
if (( ${+ATTN_SHELL_USER_ZDOTDIR} )); then
  export ZDOTDIR="$ATTN_SHELL_USER_ZDOTDIR"
else
  unset ZDOTDIR
fi
unset ATTN_SHELL_USER_ZDOTDIR
if [[ -r "${ZDOTDIR:-$HOME}/.zshenv" ]]; then
  . "${ZDOTDIR:-$HOME}/.zshenv"
fi

_attn_deferred_init() {
  precmd_functions=(${precmd_functions:#_attn_deferred_init})
` + attnDirFirstOnPath + `  if [[ -z "${ATTN_NO_SHELL_INTEGRATION-}" && -r "$ATTN_SHELL_INIT_DIR/` + zshIntegrationFile + `" ]]; then
    . "$ATTN_SHELL_INIT_DIR/` + zshIntegrationFile + `"
    _attn_osc133_precmd
  fi
  unset ATTN_SHELL_INIT_DIR ATTN_SHELL_ATTN_DIR
  unfunction _attn_deferred_init
}
typeset -ga precmd_functions
precmd_functions+=(_attn_deferred_init)
`

const attnDirFirstOnPath = `if [ -n "${ATTN_SHELL_ATTN_DIR-}" ]; then
  attn_rest="$PATH:"
  attn_path="$ATTN_SHELL_ATTN_DIR"
  while [ -n "$attn_rest" ]; do
    attn_entry="${attn_rest%%:*}"
    attn_rest="${attn_rest#*:}"
    if [ "$attn_entry" != "$ATTN_SHELL_ATTN_DIR" ]; then
      attn_path="$attn_path:$attn_entry"
    fi
  done
  PATH="$attn_path"
  export PATH
  unset attn_rest attn_path attn_entry
fi
`

const restoreUserENV = `case "${ATTN_SHELL_USER_ENV_IS_SET-}" in
1)
  ENV="$ATTN_SHELL_USER_ENV"
  export ENV
  ;;
0) unset ENV ;;
esac
`

const (
	bashStartupFile = "attn-startup.bash"
	shStartupFile   = "attn-startup.sh"
)

func startupENV(env []string, file string) []string {
	userEnv, userEnvSet := LookupEnv(env, "ENV")
	return []string{
		"ENV=" + file,
		"ATTN_SHELL_USER_ENV=" + userEnv,
		"ATTN_SHELL_USER_ENV_IS_SET=" + boolEnvValue(userEnvSet),
	}
}

func isMacOSSystemBash(shellPath string) bool {
	return runtime.GOOS == "darwin" && shellPath == "/bin/bash"
}

func prepareBashShellPaneLaunch(shellPath string, env []string, attnDir string) (shellPaneLaunch, error) {
	overlay, err := os.MkdirTemp("", "attn-bash-startup-")
	if err != nil {
		return shellPaneLaunch{}, fmt.Errorf("create bash startup overlay: %w", err)
	}
	for file, content := range map[string]string{bashStartupFile: bashLoginStartup, bashIntegrationFile: bashOSC133Integration} {
		if err := os.WriteFile(filepath.Join(overlay, file), []byte(content), 0o600); err != nil {
			_ = os.RemoveAll(overlay)
			return shellPaneLaunch{}, fmt.Errorf("write bash startup overlay %s: %w", file, err)
		}
	}
	rc := filepath.Join(overlay, bashStartupFile)
	startEnv := []string{"ATTN_SHELL_INIT_DIR=" + overlay, "ATTN_SHELL_ATTN_DIR=" + attnDir}
	if isMacOSSystemBash(shellPath) {
		return shellPaneLaunch{
			command:    exec.Command(shellPath, "--rcfile", rc, "-i"),
			env:        MergeEnvironment(env, startEnv),
			overlayDir: overlay,
		}, nil
	}
	return shellPaneLaunch{
		command:    exec.Command(shellPath, "--posix", "-l"),
		env:        MergeEnvironment(env, append(startEnv, startupENV(env, rc)...)),
		overlayDir: overlay,
	}, nil
}

const bashLoginStartup = `# Generated by attn. Run bash's login startup, as bash -l would, then
# put the active attn first on the PATH that startup built.
set +o posix
shopt -u inherit_errexit 2>/dev/null
case "$(declare -p HISTFILE 2>/dev/null)" in
"declare -x"*) ;;
*) HISTFILE="$HOME/.bash_history" ;;
esac
` + restoreUserENV + `if [ -r /etc/profile ]; then
  . /etc/profile
fi
if [ -r "$HOME/.bash_profile" ]; then
  . "$HOME/.bash_profile"
elif [ -r "$HOME/.bash_login" ]; then
  . "$HOME/.bash_login"
elif [ -r "$HOME/.profile" ]; then
  . "$HOME/.profile"
fi
` + attnDirFirstOnPath + `if [ -z "${ATTN_NO_SHELL_INTEGRATION-}" ] && [ -r "$ATTN_SHELL_INIT_DIR/` + bashIntegrationFile + `" ]; then
  . "$ATTN_SHELL_INIT_DIR/` + bashIntegrationFile + `"
fi
unset ATTN_SHELL_INIT_DIR ATTN_SHELL_ATTN_DIR ATTN_SHELL_USER_ENV ATTN_SHELL_USER_ENV_IS_SET
`

func prepareShShellPaneLaunch(shellPath string, env []string, attnDir string) (shellPaneLaunch, error) {
	overlay, err := os.MkdirTemp("", "attn-sh-startup-")
	if err != nil {
		return shellPaneLaunch{}, fmt.Errorf("create sh startup overlay: %w", err)
	}
	startup := filepath.Join(overlay, shStartupFile)
	if err := os.WriteFile(startup, []byte(shStartupEnv), 0o600); err != nil {
		_ = os.RemoveAll(overlay)
		return shellPaneLaunch{}, fmt.Errorf("write sh startup overlay: %w", err)
	}
	return shellPaneLaunch{
		command:    exec.Command(shellPath, "-i"),
		env:        MergeEnvironment(env, append(startupENV(env, startup), "ATTN_SHELL_ATTN_DIR="+attnDir)),
		overlayDir: overlay,
	}, nil
}

const shStartupEnv = `# Generated by attn. Run sh's login startup and the user's $ENV, as
# sh -l would, then put the active attn first on the PATH they built.
` + restoreUserENV + `if [ -r /etc/profile ]; then
  . /etc/profile
fi
if [ -r "$HOME/.profile" ]; then
  . "$HOME/.profile"
fi
if [ -n "${ENV-}" ] && [ -r "$ENV" ]; then
  . "$ENV"
fi
` + attnDirFirstOnPath + `unset ATTN_SHELL_ATTN_DIR ATTN_SHELL_USER_ENV ATTN_SHELL_USER_ENV_IS_SET
`

func LookupEnv(env []string, key string) (string, bool) {
	prefix := key + "="
	for _, entry := range env {
		if strings.HasPrefix(entry, prefix) {
			return strings.TrimPrefix(entry, prefix), true
		}
	}
	return "", false
}

func boolEnvValue(value bool) string {
	if value {
		return "1"
	}
	return "0"
}

func ShellIntegrationExpected(path string, env []string) bool {
	if disabled, _ := LookupEnv(env, "ATTN_NO_SHELL_INTEGRATION"); disabled != "" {
		return false
	}
	switch shellKind(path) {
	case "fish", "zsh", "bash":
		return true
	}
	return false
}
